"""Index of every Alma REST operation, built from the committed swagger snapshot.

The index is package data (``data/alma_endpoints.json``), generated by
``python -m scripts.build_lab_endpoints``. It drives the Alma Lab "Raw" console:
forms, write classification and matching of a concrete path to its operation.
"""
from __future__ import annotations

import json
import re
from dataclasses import dataclass, fields
from functools import lru_cache
from importlib import resources
from pathlib import Path
from typing import Any, Literal
from urllib.parse import unquote

API_PREFIX = "/almaws/v1"
METHODS = ("GET", "POST", "PUT", "DELETE")

AREA_TITLES: dict[str, str] = {
    "acq": "Acquisitions",
    "bibs": "Bibs",
    "conf": "Configuration",
    "courses": "Courses",
    "electronic": "Electronic",
    "partners": "Partners (resource sharing)",
    "users": "Users",
    "analytics": "Analytics",
}


@dataclass(frozen=True)
class EndpointParam:
    """One path or query parameter of an operation."""

    name: str
    location: Literal["path", "query"]
    type: str
    required: bool
    default: str | None
    description: str


@dataclass(frozen=True)
class Endpoint:
    """One Alma operation (method + path template)."""

    area: str
    method: str
    path: str
    summary: str
    description: str
    params: tuple[EndpointParam, ...]
    body_formats: tuple[str, ...]
    body_example: str | None
    source_fetched: str | None
    custom: bool = False

    @property
    def key(self) -> str:
        return f"{self.method} {self.path}"

    @property
    def writes(self) -> bool:
        return self.method != "GET"

    @property
    def short_path(self) -> str:
        return self.path.removeprefix(API_PREFIX)

    @property
    def path_params(self) -> tuple[EndpointParam, ...]:
        return tuple(p for p in self.params if p.location == "path")

    @property
    def query_params(self) -> tuple[EndpointParam, ...]:
        return tuple(p for p in self.params if p.location == "query")

    @property
    def confirm_word(self) -> str:
        literal = [s for s in self.path.split("/") if s and not s.startswith("{")]
        return f"{self.method} {literal[-1]}"

    @property
    def slug(self) -> str:
        tail = re.sub(r"[^A-Za-z0-9_]+", "-", self.short_path).strip("-")
        return f"raw-{self.method}-{tail}".strip("-")


# --- building the index ------------------------------------------------------

def _resolve(param: dict[str, Any], spec: dict[str, Any]) -> dict[str, Any]:
    ref = param.get("$ref")
    if not ref:
        return param
    node: Any = spec
    for part in ref.lstrip("#/").split("/"):
        node = node[part]
    return node


def _param(raw: dict[str, Any]) -> dict[str, Any] | None:
    if raw.get("in") not in ("path", "query"):
        return None
    schema = raw.get("schema") or {}
    default = schema.get("default")
    return {
        "name": raw["name"],
        "location": raw["in"],
        "type": schema.get("type") or raw.get("type") or "string",
        "required": bool(raw.get("required")) or raw["in"] == "path",
        "default": None if default is None else str(default),
        "description": (raw.get("description") or "").strip(),
    }


def _merge_params(spec: dict, path_item: dict, op: dict) -> list[dict[str, Any]]:
    merged: dict[tuple[str, str], dict[str, Any]] = {}
    for raw in list(path_item.get("parameters", [])) + list(op.get("parameters", [])):
        p = _param(_resolve(raw, spec))
        if p:
            merged[(p["location"], p["name"])] = p
    return list(merged.values())


def _body(op: dict[str, Any]) -> tuple[list[str], str | None]:
    content = (op.get("requestBody") or {}).get("content") or {}
    formats = [f for f in ("json", "xml") if any(f in ct for ct in content)]
    example = None
    for fmt in formats:
        for ct, media in content.items():
            if fmt in ct and "example" in media:
                ex = media["example"]
                example = ex if isinstance(ex, str) else json.dumps(ex, indent=2)
                return formats, example
    return formats, example


def build_index(swagger_dir: Path) -> dict:
    """Build the endpoint index from every ``<area>.json`` in ``swagger_dir``."""
    sources: dict[str, str | None] = {}
    endpoints: list[dict[str, Any]] = []
    for spec_file in sorted(Path(swagger_dir).glob("*.json")):
        if spec_file.name.endswith(".fetched.json"):
            continue
        area = spec_file.stem
        sidecar = spec_file.with_name(f"{area}.fetched.json")
        fetched = None
        if sidecar.exists():
            fetched = json.loads(sidecar.read_text("utf-8")).get("fetchedAt")
        sources[area] = fetched
        spec = json.loads(spec_file.read_text("utf-8"))
        for path, item in spec.get("paths", {}).items():
            for method in METHODS:
                op = item.get(method.lower())
                if not op:
                    continue
                formats, example = _body(op)
                endpoints.append({
                    "area": area,
                    "method": method,
                    "path": path,
                    "summary": (op.get("summary") or "").strip(),
                    "description": (op.get("description") or "").strip(),
                    "params": _merge_params(spec, item, op),
                    "body_formats": formats,
                    "body_example": example,
                    "source_fetched": fetched,
                    "custom": False,
                })
    endpoints.sort(key=lambda e: (e["area"], e["path"], METHODS.index(e["method"])))
    return {"sources": sources, "endpoints": endpoints}


# --- reading the bundled index ------------------------------------------------

def _from_dict(d: dict[str, Any]) -> Endpoint:
    known = {f.name for f in fields(Endpoint)}
    data = {k: v for k, v in d.items() if k in known}
    data["params"] = tuple(EndpointParam(**p) for p in d["params"])
    data["body_formats"] = tuple(d["body_formats"])
    return Endpoint(**data)


@lru_cache(maxsize=1)
def load_endpoints() -> tuple[Endpoint, ...]:
    """All indexed operations (cached)."""
    text = resources.files("almaapitk.lab.data").joinpath("alma_endpoints.json").read_text("utf-8")
    return tuple(_from_dict(d) for d in json.loads(text)["endpoints"])


def get_endpoint(method: str, path: str) -> Endpoint:
    """Return the operation for an exact template; KeyError if absent."""
    method = method.upper()
    for ep in load_endpoints():
        if ep.method == method and ep.path == path:
            return ep
    raise KeyError(f"{method} {path}")


def get_twin(endpoint: Endpoint) -> Endpoint | None:
    """The GET on the same path (used to prefill an update), if any."""
    for ep in load_endpoints():
        if ep.method == "GET" and ep.path == endpoint.path:
            return ep
    return None


def _segments(path: str) -> list[str]:
    path = "/" + path.strip("/")
    if path.startswith(API_PREFIX + "/") or path == API_PREFIX:
        path = path[len(API_PREFIX):]
    return [s for s in path.split("/") if s]


def _match_in(
    candidates: tuple[Endpoint, ...], method: str, concrete_path: str
) -> tuple[Endpoint, dict[str, str]] | None:
    method = method.upper()
    segs = _segments(concrete_path)
    best: tuple[int, Endpoint, dict[str, str]] | None = None
    for ep in candidates:
        if ep.method != method:
            continue
        tmpl = _segments(ep.short_path)
        if len(tmpl) != len(segs):
            continue
        values: dict[str, str] = {}
        literals = 0
        for t, s in zip(tmpl, segs):
            if t.startswith("{") and t.endswith("}"):
                values[t[1:-1]] = unquote(s)
            elif t == s:
                literals += 1
            else:
                break
        else:
            if best is None or literals > best[0]:
                best = (literals, ep, values)
    return None if best is None else (best[1], best[2])


def match(method: str, concrete_path: str) -> tuple[Endpoint, dict[str, str]] | None:
    """Match a concrete path to an indexed operation and extract path values."""
    return _match_in(load_endpoints(), method, concrete_path)


def custom_endpoint(method: str, path: str) -> Endpoint:
    """An operation the index does not know (no params, free-form body)."""
    method = method.upper()
    path = re.split(r"[?#]", path, maxsplit=1)[0].strip()
    path = "/" + path.strip("/")
    if not any(s and not s.startswith("{") for s in path.split("/")):
        raise ValueError(
            "custom path needs at least one fixed segment, e.g. almaws/v1/task-lists/..."
        )
    return Endpoint(
        area="custom",
        method=method,
        path=path,
        summary="",
        description="",
        params=(),
        body_formats=("json", "xml") if method in ("POST", "PUT") else (),
        body_example=None,
        source_fetched=None,
        custom=True,
    )


# --- which almaapitk methods already call an endpoint ------------------------

@lru_cache(maxsize=1)
def _wrapped_map() -> dict[tuple[str, str], tuple[str, ...]]:
    from almaapitk.lab.catalog import DOMAINS, discover_operations, endpoint_calls

    by_key: dict[tuple[str, str], set[str]] = {}
    for op in discover_operations():
        for verb, template in endpoint_calls(DOMAINS[op.domain], op.name):
            key = (verb, re.sub(r"\{[^}]*\}", "{}", template))
            by_key.setdefault(key, set()).add(op.qualname)
    return {k: tuple(sorted(v)) for k, v in by_key.items()}


def wrapped_by(endpoint: Endpoint) -> tuple[str, ...]:
    """Sorted ``Domain.method`` names of public almaapitk operations that call it."""
    key = (endpoint.method, re.sub(r"\{[^}]*\}", "{}", endpoint.path))
    return _wrapped_map().get(key, ())
